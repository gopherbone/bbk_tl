def _parse(art: str) -> dict[str, list[str]]:
    glyphs: dict[str, list[str]] = {}
    lines = art.strip("\n").split("\n")
    i = 0
    while i < len(lines):
        head = lines[i].rstrip()
        if not head:
            i += 1
            continue
        if not (len(head) >= 3 and head[0] in "'\"" and head[-1] == head[0]):
            raise ValueError(f"bad glyph header at line {i + 1}: {head!r}")
        ch = head[1:-1]
        rows = [r.rstrip() for r in lines[i + 1:i + 1 + H]]
        w = max(len(r) for r in rows)
        rows = [r.ljust(w, ".") for r in rows]
        if any(set(r) - {"#", "."} for r in rows):
            raise ValueError(f"bad pixels in glyph {ch!r}")
        glyphs[ch] = rows
        i += 1 + H
    return glyphs


GLYPHS = _parse(_ART)


def width(ch: str) -> int:
    return len(GLYPHS.get(ch, GLYPHS["?"])[0])


def text_width(s: str, spacing: int = 1) -> int:
    return sum(width(c) + spacing for c in s) - (spacing if s else 0)
